-- PROFILES
CREATE TABLE IF NOT EXISTS profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    nome TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('consumidor', 'gerador', 'parceiro', 'admin')),
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    whatsapp TEXT NOT NULL,
    cidade TEXT NOT NULL,
    estado TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login TIMESTAMPTZ,
    is_active BOOLEAN NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS idx_profiles_tipo ON profiles(tipo);
CREATE INDEX IF NOT EXISTS idx_profiles_role ON profiles(role);

-- LEADS
CREATE TABLE IF NOT EXISTS leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    email TEXT NOT NULL,
    whatsapp TEXT NOT NULL,
    cidade TEXT NOT NULL,
    estado TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('consumidor', 'gerador', 'parceiro')),
    capacidade_kwp FLOAT,
    gasto_mensal FLOAT,
    concessionaria TEXT,
    nicho TEXT,
    audiencia_estimada INTEGER,
    canal TEXT,
    status TEXT NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'aprovado', 'recusado')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processed_at TIMESTAMPTZ,
    processed_by UUID REFERENCES profiles(id),
    observacoes TEXT,
    embaixador_id UUID REFERENCES auth.users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_leads_status ON leads(status);
CREATE INDEX IF NOT EXISTS idx_leads_tipo ON leads(tipo);
CREATE INDEX IF NOT EXISTS idx_leads_user_id ON leads(user_id);
CREATE INDEX IF NOT EXISTS idx_leads_embaixador ON leads(embaixador_id);

-- GERADORES
CREATE TABLE IF NOT EXISTS geradores (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    nome_usina TEXT NOT NULL,
    capacidade_kwp FLOAT NOT NULL CHECK (capacidade_kwp > 0),
    excedente_mensal_kwh FLOAT NOT NULL CHECK (excedente_mensal_kwh > 0),
    concessionaria TEXT NOT NULL,
    cidade TEXT NOT NULL,
    estado TEXT NOT NULL,
    endereco TEXT,
    latitude FLOAT,
    longitude FLOAT,
    status TEXT NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'aprovado', 'ativo', 'inativo')),
    data_aprovacao TIMESTAMPTZ,
    lucro_total DECIMAL(12,2) DEFAULT 0.00,
    kwh_vendidos_total INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_geradores_status ON geradores(status);

-- CONSUMIDORES
CREATE TABLE IF NOT EXISTS consumidores (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    gasto_mensal FLOAT NOT NULL CHECK (gasto_mensal > 0),
    economia_mensal DECIMAL(10,2) DEFAULT 0.00,
    economia_total DECIMAL(12,2) DEFAULT 0.00,
    kwh_consumidos INTEGER DEFAULT 0,
    co2_evitado_kg INTEGER DEFAULT 0,
    arvores_salvas INTEGER DEFAULT 0,
    plano_ativo BOOLEAN DEFAULT false,
    data_primeira_assinatura TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ASSINATURAS
CREATE TABLE IF NOT EXISTS assinaturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    stripe_subscription_id TEXT UNIQUE NOT NULL,
    stripe_price_id TEXT NOT NULL,
    nome_plano TEXT NOT NULL,
    valor_mensal DECIMAL(10,2) NOT NULL,
    kwh_mensais INTEGER NOT NULL,
    economia_percentual INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'past_due', 'canceled', 'unpaid')),
    current_period_start TIMESTAMPTZ NOT NULL,
    current_period_end TIMESTAMPTZ NOT NULL,
    cancel_at_period_end BOOLEAN DEFAULT false,
    trial_end TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    canceled_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_assinaturas_user_id ON assinaturas(user_id);
CREATE INDEX IF NOT EXISTS idx_assinaturas_status ON assinaturas(status);

-- COMISSOES
CREATE TABLE IF NOT EXISTS comissoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    embaixador_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    cliente_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    lead_id BIGINT REFERENCES leads(id) ON DELETE CASCADE,
    valor_comissao DECIMAL(10,2) NOT NULL,
    percentual INTEGER NOT NULL CHECK (percentual > 0 AND percentual <= 100),
    tipo_comissao TEXT NOT NULL CHECK (tipo_comissao IN ('cadastro', 'recorrente', 'match', 'embaixador_5pct', 'ufv_15pct')),
    status_pagamento TEXT NOT NULL DEFAULT 'pendente' CHECK (status_pagamento IN ('pendente', 'pago', 'cancelado')),
    data_pagamento TIMESTAMPTZ,
    stripe_payment_intent TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    mes_referencia DATE NOT NULL DEFAULT date_trunc('month', NOW())::date,
    ano_referencia INTEGER NOT NULL DEFAULT EXTRACT(year FROM NOW())::integer
);
CREATE INDEX IF NOT EXISTS idx_comissoes_embaixador_id ON comissoes(embaixador_id);
CREATE INDEX IF NOT EXISTS idx_comissoes_cliente_id ON comissoes(cliente_id);
CREATE INDEX IF NOT EXISTS idx_comissoes_status_pagamento ON comissoes(status_pagamento);
CREATE INDEX IF NOT EXISTS idx_comissoes_tipo_comissao ON comissoes(tipo_comissao);

-- PAGAMENTOS
CREATE TABLE IF NOT EXISTS pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    tipo_pagamento TEXT NOT NULL CHECK (tipo_pagamento IN ('assinatura', 'comissao', 'adicional')),
    valor DECIMAL(10,2) NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'succeeded', 'failed', 'refunded')),
    stripe_payment_intent TEXT UNIQUE,
    stripe_charge_id TEXT,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_pagamentos_user_id ON pagamentos(user_id);
CREATE INDEX IF NOT EXISTS idx_pagamentos_tipo_pagamento ON pagamentos(tipo_pagamento);
CREATE INDEX IF NOT EXISTS idx_pagamentos_status ON pagamentos(status);
CREATE INDEX IF NOT EXISTS idx_pagamentos_created_at ON pagamentos(created_at DESC);

-- MATCHES
CREATE TABLE IF NOT EXISTS matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gerador_id UUID REFERENCES geradores(id) ON DELETE CASCADE,
    consumidor_id UUID REFERENCES consumidores(id) ON DELETE CASCADE,
