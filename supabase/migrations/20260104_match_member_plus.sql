-- ============================================
-- 5. FUNÇÃO RPC: FIND_MATCH_CANDIDATES
-- ============================================
-- Retorna candidatos (usuários do tipo oposto) dentro de um raio em km
-- Usa fórmula de Haversine para cálculo de distância

CREATE OR REPLACE FUNCTION find_match_candidates(
    p_user_id UUID,
    p_user_lat DOUBLE PRECISION,
    p_user_lng DOUBLE PRECISION,
    p_target_tipo TEXT,
    p_radius_km INTEGER DEFAULT 50,
    p_limit INTEGER DEFAULT 50
)
RETURNS TABLE (
    user_id UUID,
    nome TEXT,
    cidade TEXT,
    estado TEXT,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    distance_km DOUBLE PRECISION,
    tipo TEXT,
    is_member_plus BOOLEAN
) AS $$
BEGIN
    RETURN QUERY
    SELECT
        p.id,
        p.nome,
        ul.cidade,
        ul.estado,
        ul.lat,
        ul.lng,
        (
            6371 * acos(
                LEAST(1.0, GREATEST(-1.0,
                    cos(radians(p_user_lat)) * cos(radians(ul.lat)) *
                    cos(radians(ul.lng) - radians(p_user_lng)) +
                    sin(radians(p_user_lat)) * sin(radians(ul.lat))
                ))
            )
        )::DOUBLE PRECISION AS distance_km,
        p.tipo,
        p.member_plus_active
    FROM profiles p
    JOIN user_locations ul ON ul.user_id = p.id
    WHERE p.id != p_user_id
      AND p.tipo = p_target_tipo
      AND p.is_active = true
      AND (
          6371 * acos(
              LEAST(1.0, GREATEST(-1.0,
                  cos(radians(p_user_lat)) * cos(radians(ul.lat)) *
                  cos(radians(ul.lng) - radians(p_user_lng)) +
                  sin(radians(p_user_lat)) * sin(radians(ul.lat))
              ))
          )
      ) <= p_radius_km
    ORDER BY distance_km ASC
    LIMIT p_limit;
END;
$$ LANGUAGE plpgsql STABLE;

-- ============================================
-- 6. FUNÇÃO: AUTO-EXPIRAR PROPOSTAS
-- ============================================

CREATE OR REPLACE FUNCTION expire_old_proposals() RETURNS VOID AS $$
BEGIN
    UPDATE match_proposals
    SET status = 'expired',
        updated_at = NOW()
    WHERE status = 'pending'
      AND expires_at < NOW();
END;
$$ LANGUAGE plpgsql;

