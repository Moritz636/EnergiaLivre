-- Função para calcular comissão de cadastro
CREATE OR REPLACE FUNCTION calcular_comissao_cadastro(
    valor_plano DECIMAL(10,2),
    percentual_comissao INTEGER
) RETURNS DECIMAL(10,2) AS $$
BEGIN
    RETURN (valor_plano * percentual_comissao) / 100;
END;
$$ LANGUAGE plpgsql;

-- Função para calcular comissão recorrente
CREATE OR REPLACE FUNCTION calcular_comissao_recorrente(
    valor_assinatura DECIMAL(10,2),
    percentual_comissao INTEGER
) RETURNS DECIMAL(10,2) AS $$
BEGIN
    RETURN (valor_assinatura * percentual_comissao) / 100;
END;
$$ LANGUAGE plpgsql;

-- Função para atualizar estatísticas de consumidor
CREATE OR REPLACE FUNCTION atualizar_estatisticas_consumidor(
    consumidor_id UUID,
    gasto_mensal FLOAT,
    economia_mensal DECIMAL(10,2)
) RETURNS VOID AS $$
BEGIN
    UPDATE consumidores 
    SET 
        gasto_mensal = gasto_mensal,
        economia_mensal = economia_mensal,
        economia_total = economia_total + economia_mensal,
        kwh_consumidos = kwh_consumidos + (gasto_mensal * 0.8), -- Estimativa
        co2_evitado_kg = co2_evitado_kg + (gasto_mensal * 0.7), -- Estimativa
        arvores_salvas = arvores_salvas + (gasto_mensal * 0.01) -- Estimativa
    WHERE id = consumidor_id;
END;
$$ LANGUAGE plpgsql;

