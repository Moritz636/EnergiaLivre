-- View de estatísticas do sistema
CREATE OR REPLACE VIEW view_estatisticas_sistema AS
SELECT 
    COUNT(DISTINCT p.id) as total_usuarios,
    COUNT(DISTINCT CASE WHEN p.tipo = 'gerador' THEN p.id END) as total_geradores,
    COUNT(DISTINCT CASE WHEN p.tipo = 'consumidor' THEN p.id END) as total_consumidores,
    COUNT(DISTINCT l.id) as total_leads,
    COUNT(DISTINCT CASE WHEN l.status = 'aprovado' THEN l.id END) as leads_aprovados,
    COUNT(DISTINCT a.id) as assinaturas_ativas,
    COALESCE(SUM(a.valor_mensal), 0) as faturamento_mensal,
    COALESCE(SUM(c.valor_comissao), 0) as total_comissoes,
    COALESCE(SUM(m.valor_transacao), 0) as volume_transacoes
FROM profiles p
LEFT JOIN leads l ON p.id = l.user_id
LEFT JOIN assinaturas a ON p.id = a.user_id AND a.status = 'active'
LEFT JOIN comissoes c ON p.id = c.embaixador_id AND c.status_pagamento = 'pago'
LEFT JOIN matches m ON p.id = m.gerador_id AND m.status = 'active';

-- View de comissões pendentes
CREATE OR REPLACE VIEW view_comissoes_pendentes AS
SELECT 
    c.*,
    p.nome as embaixador_nome,
    p.email as embaixador_email,
    cli.nome as cliente_nome,
    cli.email as cliente_email
FROM comissoes c
JOIN profiles p ON c.embaixador_id = p.id
LEFT JOIN auth.users cli ON c.cliente_id = cli.id
WHERE c.status_pagamento = 'pendente';

-- View de performance de geradores
CREATE OR REPLACE VIEW view_performance_geradores AS
SELECT 
    g.id,
    g.nome_usina,
    g.capacidade_kwp,
    g.excedente_mensal_kwh,
    g.status,
    g.lucro_total,
    g.kwh_vendidos_total,
    COUNT(m.id) as total_matches,
    COALESCE(SUM(m.valor_transacao), 0) as receita_total,
    COUNT(DISTINCT a.id) as assinaturas_geradas
FROM geradores g
LEFT JOIN matches m ON g.id = m.gerador_id AND m.status = 'active'
LEFT JOIN assinaturas a ON m.consumidor_id = a.user_id AND a.status = 'active'
GROUP BY g.id, g.nome_usina, g.capacidade_kwp, g.excedente_mensal_kwh, g.status, g.lucro_total, g.kwh_vendidos_total;

