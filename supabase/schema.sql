-- Função para criar perfil automaticamente quando novo usuário se cadastra
CREATE OR REPLACE FUNCTION handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, nome, tipo, role, whatsapp, cidade, estado)
    VALUES (
        NEW.id,
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'nome', NEW.email),
        COALESCE(NEW.raw_user_meta_data->>'tipo', 'consumidor'),
        'user',
        COALESCE(NEW.raw_user_meta_data->>'whatsapp', ''),
        COALESCE(NEW.raw_user_meta_data->>'cidade', ''),
        COALESCE(NEW.raw_user_meta_data->>'estado', '')
    );
    
    -- Criar entry correspondente na tabela específica (gerador ou consumidor)
    IF COALESCE(NEW.raw_user_meta_data->>'tipo', 'consumidor') = 'gerador' THEN
        INSERT INTO public.geradores (id, nome_usina, capacidade_kwp, excedente_mensal_kwh, concessionaria, cidade, estado, status)
        VALUES (
            NEW.id,
            COALESCE(NEW.raw_user_meta_data->>'nome_usina', 'Usina Solar'),
            COALESCE(NEW.raw_user_meta_data->>'capacidade_kwp', 0)::FLOAT,
            COALESCE(NEW.raw_user_meta_data->>'excedente_mensal_kwh', 0)::FLOAT,
            COALESCE(NEW.raw_user_meta_data->>'concessionaria', ''),
            COALESCE(NEW.raw_user_meta_data->>'cidade', ''),
            COALESCE(NEW.raw_user_meta_data->>'estado', ''),
            'pendente'
        );
    ELSE
        INSERT INTO public.consumidores (id, gasto_mensal)
        VALUES (
            NEW.id,
            COALESCE(NEW.raw_user_meta_data->>'gasto_mensal', 0)::FLOAT
        );
    END IF;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger para criar perfil automaticamente
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION handle_new_user();

