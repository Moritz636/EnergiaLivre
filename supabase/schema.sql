-- ============================================
-- TABELA PRINCIPAL: PROFILES (PERFIS DE USUÁRIOS)
-- ============================================
CREATE TABLE IF NOT EXISTS profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    nome TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('consumidor', 'gerador', 'admin')),
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    whatsapp TEXT NOT NULL,
    cidade TEXT NOT NULL,
    estado TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login TIMESTAMPTZ,
    is_active BOOLEAN NOT NULL DEFAULT true
);

-- Índices para performance
CREATE INDEX idx_profiles_tipo ON profiles(tipo);
CREATE INDEX idx_profiles_role ON profiles(role);
CREATE INDEX idx_profiles_cidade ON profiles(cidade);
CREATE INDEX idx_profiles_estado ON profiles(estado);

-- ============================================
-- TABELA: LEADS (OPORTUNIDADES DE NEGÓCIO)
-- ============================================
